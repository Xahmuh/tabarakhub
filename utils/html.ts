/**
 * Escapes untrusted text before interpolating it into an HTML string.
 * Prefer React rendering or SweetAlert's `text` option whenever possible.
 */
export const escapeHtml = (value: unknown): string =>
  String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
